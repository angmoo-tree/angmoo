import {test,expect} from "@playwright/test";
const TARGET="019f1000-0000-7000-8000-000000000001", SURVIVOR="019f1000-0000-7000-8000-000000000002";
test("real isolated backend erases World and keeps reusable first source",async({page,context,baseURL})=>{
  await context.addCookies([{name:"angmoo_browser_session",value:"synthetic-lifecycle-session-not-a-user-secret",url:String(baseURL),httpOnly:true,sameSite:"Lax"}]);
  await page.route("**/*",route=>new URL(route.request().url()).origin===new URL(String(baseURL)).origin?route.fallback():route.abort("blockedbyclient"));
  await page.goto("/studio");
  const card=page.getByRole("article").filter({has:page.getByRole("heading",{name:"Integration target",exact:true})});
  await expect(card).toBeVisible();
  await card.getByRole("button",{name:"Delete World",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByRole("textbox",{name:"Enter the World name to confirm.",exact:true}).fill("Integration target");
  await dialog.getByRole("checkbox",{name:"I confirm permanent deletion.",exact:true}).check();
  await dialog.getByRole("button",{name:"Permanently delete",exact:true}).click();
  await expect(page.getByText("World deleted.",{exact:true})).toBeVisible();
  await expect(card).toHaveCount(0);
  await expect(page.getByRole("heading",{name:"Integration survivor",exact:true})).toBeVisible();
  const request=context.request;
  const source=await request.get(`${baseURL}/api/backend/agents/fixture-red`);
  expect(source.status()).toBe(200);
  expect((await source.json()).character.personality).toBe("first registration persona");
  expect((await request.get(`${baseURL}/media/characters/fixture-red/initial.webp`)).status()).toBe(200);
  expect((await request.get(`${baseURL}/media/worlds/${TARGET}/icon-fixture.webp`)).status()).toBe(410);
  const candidates=await request.get(`${baseURL}/api/backend/worlds/${SURVIVOR}/character-candidates`);
  expect(candidates.status()).toBe(200);
  expect((await candidates.json()).items.some((item:{character_id:string;eligible:boolean})=>item.character_id==="fixture-red"&&item.eligible)).toBe(true);
  const headers={Origin:String(baseURL)};
  const copy=await request.post(`${baseURL}/api/backend/agents/drafts/fixture-copy-draft/copy-settings`,{headers,data:{revision:1,character_id:"fixture-red"}});
  expect(copy.status()).toBe(200);
  expect((await copy.json()).personality).toBe("first registration persona");
  const registered=await request.post(`${baseURL}/api/backend/worlds/${SURVIVOR}/characters`,{headers,data:{character_id:"fixture-red",role_key:"no_specific_role",idempotency_key:"synthetic-explicit-registration"}});
  expect(registered.status()).toBe(201);
  expect((await registered.json()).autonomous_enabled).toBe(false);
  await page.screenshot({path:"../artifacts/chat-world-lifecycle-20261012/real-browser/world-deleted.png",fullPage:true});
});
